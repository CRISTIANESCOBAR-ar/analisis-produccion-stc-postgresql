/**
 * Obtiene el sector asociado a un código de defecto.
 * Retorna 'DESCONOCIDO' si el código no está mapeado.
 */
export function getSectorByCodDef(codDef) {
  if (!codDef) return 'DESCONOCIDO';
  const numCod = parseInt(String(codDef).trim(), 10);
  return defectoSectorMap[numCod] || 'DESCONOCIDO';
}
